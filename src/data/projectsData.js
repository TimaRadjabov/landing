function imageUrl(folder, image) {
  // Vite dev server fails to resolve %2C (comma) and %2B (plus) in static paths
  const enc = s => encodeURIComponent(s).replace(/%2C/gi, ',').replace(/%2B/gi, '+');
  return `/images/${enc(folder)}/${enc(image)}`;
}

